'use strict';

// Leave internal routing values and legacy source-patch anchors intact.
// Only labels rendered by the interface lose their old screen identifiers.
module.exports = function hideScreenCodes({ types: t }) {
  const codePattern = /#S-\d{2,4}\b/g;
  const hasCode = (value) => /#S-\d{2,4}\b/.test(value);
  const clean = (value) => value.replace(codePattern, '').replace(/^\s*[·:|]\s*|\s*[·:|]\s*$/g, '').replace(/[ \t]{2,}/g, ' ').trim();
  const labelKeys = new Set(['title', 'subtitle', 'label', 'text', 'children', 'placeholder', 'accessibilityLabel', 'accessibilityHint']);
  const propertyName = (node) => t.isIdentifier(node) || t.isJSXIdentifier(node) ? node.name : t.isStringLiteral(node) ? node.value : '';
  const textValue = (node) => {
    if (t.isJSXText(node)) return node.value;
    if (t.isJSXExpressionContainer(node) && t.isStringLiteral(node.expression)) return node.expression.value;
    return null;
  };
  const cleanString = (path) => {
    if (!hasCode(path.node.value)) return;
    const parent = path.parentPath;
    const attribute = parent?.isJSXAttribute() ? parent : parent?.isJSXExpressionContainer() && parent.parentPath?.isJSXAttribute() ? parent.parentPath : null;
    if (attribute && labelKeys.has(propertyName(attribute.node.name))) { path.node.value = clean(path.node.value); return; }
    if (parent?.isJSXExpressionContainer() && parent.parentPath?.isJSXElement()) { path.node.value = clean(path.node.value); return; }
    let value = path;
    while (value.parentPath?.isArrayExpression()) value = value.parentPath;
    const property = value.parentPath;
    if (property?.isObjectProperty() && property.node.value === value.node && labelKeys.has(propertyName(property.node.key))) path.node.value = clean(path.node.value);
  };
  return {
    name: 'hide-screen-codes',
    visitor: {
      JSXElement(path) {
        const opening = path.node.openingElement;
        if (!t.isJSXIdentifier(opening.name, { name: 'Text' })) return;
        const values = path.node.children.map(textValue);
        if (values.some((value) => value === null)) return;
        const text = values.join('');
        if (hasCode(text) && !clean(text)) path.remove();
      },
      JSXText(path) { if (hasCode(path.node.value)) path.node.value = clean(path.node.value); },
      StringLiteral: cleanString,
      Program: {
        exit(path, state) {
          // Catch labels generated by earlier Babel UI adapters as well.
          if (String(state.filename || '').includes('babel-plugin-')) return;
          path.traverse({ StringLiteral: cleanString });
        },
      },
    },
  };
};
